/* ============================================================
   tools/dev/heptapod_equations.mjs — the equations sheet of the
   inked script, generated from the code (Luis, 2026-11-18: "we don't
   want handwaved, it will be generated obeying mathematical
   equations").

     node tools/dev/heptapod_equations.mjs

   1. Every constant of topo/inkfig.js's INK with its kind from
      INK_KIND: derived, calibrated (to a named film measure), frame,
      or chosen (set by eye or a first value: debt).
   2. The numeric literals still written inline in the drawing code
      (comments removed; 0, 1, 2, 0.5, the 1.89 and 9.02 of the
      thread's physics, 360 and 180 excepted), each with its line: the
      debt the constants do not show.
   Writes labs/assets/data/heptapod/equations.json and prints the
   counts. Exits 1 when a constant has no kind (a new constant must be
   classed when it is added).
   ============================================================ */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { INK, INK_KIND } from '../../labs/assets/js/heptapod/topo/inkfig.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.join(HERE, '../../labs/assets/js/heptapod/topo/inkfig.js');
const OUT = path.join(HERE, '../../labs/assets/data/heptapod/equations.json');

const constants = Object.keys(INK).filter((k) => k !== 'version').map((k) => ({ name: k, value: INK[k], kind: INK_KIND[k]?.[0] ?? null, source: INK_KIND[k]?.[1] ?? null }));
const unclassed = constants.filter((c) => !c.kind).map((c) => c.name);

// numeric literals inline in the drawing code, outside the INK and INK_KIND blocks, comments removed
const src = fs.readFileSync(SRC, 'utf8');
const lines = src.split('\n');
let inBlock = false, inComment = false;
const KEEP = new Set(['0', '1', '2', '0.5', '1.89', '9.02', '360', '180']);
const inline = [];
lines.forEach((raw, i) => {
  let line = raw;
  if (/^export const (INK|INK_KIND|INK_CALIBRATIONS) = Object\.freeze/.test(line)) inBlock = true;
  if (inBlock) { if (/^\]?\}?\);\s*$/.test(line) || /^\]\);\s*$/.test(line)) inBlock = false; return; }
  // strip block comments spanning lines, then line comments and strings
  if (inComment) { const e = line.indexOf('*/'); if (e < 0) return; line = line.slice(e + 2); inComment = false; }
  line = line.replace(/\/\*.*?\*\//g, '');
  const b = line.indexOf('/*'); if (b >= 0) { line = line.slice(0, b); inComment = true; }
  line = line.replace(/\/\/.*$/, '').replace(/`[^`]*`|'[^']*'|"[^"]*"/g, '');
  const nums = (line.match(/(?<![\w.])\d+\.?\d*(?![\w.])/g) || []).filter((n) => !KEEP.has(n) && !/^0x/.test(n));
  if (nums.length) inline.push({ line: i + 1, literals: nums });
});
const count = inline.reduce((a, r) => a + r.literals.length, 0);
const byKind = constants.reduce((m, c) => ((m[c.kind || 'unclassed'] = (m[c.kind || 'unclassed'] || 0) + 1), m), {});
const sheet = {
  about: 'The equations sheet of the inked script (topo/inkfig.js), generated by tools/dev/heptapod_equations.mjs. chosen and the inline literals are the debt: each is to be derived from physics or the grammar, or fitted by a stated objective on held-out sentences (Luis, 2026-11-18).',
  version: INK.version, constantsByKind: byKind, inlineLiterals: count, inlineLines: inline.length, constants, inline,
};
fs.writeFileSync(OUT, JSON.stringify(sheet, null, 1));
console.log(`${INK.version}: constants ${JSON.stringify(byKind)}; inline literals ${count} on ${inline.length} lines; wrote ${OUT}`);
if (unclassed.length) { console.error(`unclassed constants: ${unclassed.join(', ')}`); process.exit(1); }
