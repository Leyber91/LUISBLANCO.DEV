/* ============================================================
   tools/dev/heptapod_bible.mjs — the lab's logogram bible, generated
   (BAR_F order of 2026-11-16: "so logogram bible it is").

     node tools/dev/heptapod_bible.mjs <out dir>

   Every entry comes from the lab's own code and spec, never from hand-
   written content (ROAD section 4): today, the code of F3 (topo/code.js):
   each partition with what it is for, and every word drawn as its cells
   bending the line out, keeping it flat or bending it in. The ink is
   achromatic (BAR_F G11); grey marks the cell boundaries, an analysis
   mark. The grammar (PLAN 3.2 and 3.6 as data) and the vocabulary (E9)
   join it as they are built.
   ============================================================ */

import fs from 'node:fs';
import path from 'node:path';
import { theCode, partition, PARTITIONS, CODE_SEED, digits, show, K, RUN, DIST } from '../../labs/assets/js/heptapod/topo/code.js';

const out = process.argv[2];
if (!out) { console.error('usage: heptapod_bible.mjs <out dir>'); process.exit(2); }

const code = theCode();
const { parts, short } = partition(code);

/* one word as a line of K cells: the offset of each cell is -a, 0 or +a, joined by a smooth curve */
const CELL = 14, A = 7, PAD = 6;
function glyph(w) {
  const d = digits(w), Wd = K * CELL + 2 * PAD, Hd = 2 * A + 2 * PAD + 4;
  const pts = [[PAD, Hd / 2]];
  for (let i = 0; i < K; i++) pts.push([PAD + (i + 0.5) * CELL, Hd / 2 - (d[i] - 1) * A]);
  pts.push([PAD + K * CELL, Hd / 2]);
  // Catmull-Rom through the points, as cubic Beziers
  let p = `M${pts[0][0]} ${pts[0][1]}`;
  for (let i = 0; i < pts.length - 1; i++) {
    const p0 = pts[Math.max(0, i - 1)], p1 = pts[i], p2 = pts[i + 1], p3 = pts[Math.min(pts.length - 1, i + 2)];
    const c1 = [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6], c2 = [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6];
    p += ` C${c1[0].toFixed(1)} ${c1[1].toFixed(1)} ${c2[0].toFixed(1)} ${c2[1].toFixed(1)} ${p2[0].toFixed(1)} ${p2[1].toFixed(1)}`;
  }
  let ticks = '';
  for (let i = 0; i <= K; i++) ticks += `<line x1="${PAD + i * CELL}" y1="${Hd / 2 - A - 2}" x2="${PAD + i * CELL}" y2="${Hd / 2 + A + 2}" stroke="#c8c8c8" stroke-width="0.6"/>`;
  return `<svg viewBox="0 0 ${Wd} ${Hd}" width="${Wd}" height="${Hd}" role="img" aria-label="${show(w)}">${ticks}<path d="${p}" fill="none" stroke="#111" stroke-width="2.2" stroke-linecap="round"/></svg>`;
}

const sections = PARTITIONS.map(([name, n, kind, purpose]) => {
  const items = parts[name];
  const cells = kind === 'pair'
    ? items.map(([a, f], i) => `<div class="w pair"><span class="n">${i + 1}</span>${glyph(a)}${glyph(f)}<code>${show(a)}</code></div>`).join('')
    : items.map((w, i) => `<div class="w"><span class="n">${i + 1}</span>${glyph(w)}<code>${show(w)}</code></div>`).join('');
  return `<section><h2>${name} <small>${items.length} of ${n} ${kind === 'pair' ? 'pairs (affirmed, then denied)' : 'words'}</small></h2><p>${purpose}.</p><div class="g">${cells}</div></section>`;
}).join('');

const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Logogram bible: the code</title><style>
body{margin:0;padding:28px 32px;background:#fbfbf9;color:#1a1a1a;font:15px/1.5 Georgia,serif;max-width:1500px}
h1{font-size:24px;margin:0 0 4px}h2{font-size:18px;margin:26px 0 2px}h2 small{font-weight:normal;color:#555;font-size:14px}
p{margin:2px 0 10px;color:#333}.g{display:flex;flex-wrap:wrap;gap:6px 14px}.w{display:flex;align-items:center;gap:6px}
.n{font:11px/1 ui-monospace,monospace;color:#888;width:22px;text-align:right}code{font:11px ui-monospace,monospace;color:#666}
.lead{color:#333;max-width:900px}
</style></head><body>
<h1>The logogram bible. Part 1: the code</h1>
<p class="lead">Generated by tools/dev/heptapod_bible.mjs from topo/code.js; nothing on this page is written by hand. A word is ${K} cells along the edge of a shape; each cell bends the line out, keeps it flat, or bends it in. The ${code.words.length} words (${code.pairs.length} pairs, seed ${CODE_SEED}) can be read from any cell, because no word appears inside two others side by side; no word is another read backwards, so a mirror shows; no more than ${RUN} cells in a row are the same; any two words differ in at least ${DIST} cells, so one misread cell is not a word. Denying a concept flips its cells, out for in.${Object.keys(short).length ? ' Short: ' + JSON.stringify(short) + '.' : ''}</p>
${sections}
</body></html>`;
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'bible-code.html'), html);
console.log(`wrote ${path.join(out, 'bible-code.html')}: ${code.words.length} words in ${PARTITIONS.length} partitions`);
