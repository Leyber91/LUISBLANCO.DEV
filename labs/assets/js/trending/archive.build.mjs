/* ============================================================
   trending/archive.build.mjs — writes archive.data.js, the dated
   record the page imports so it is never empty at rest:
     latest   the newest recorded scan of every source (full record)
     trail    earlier recorded scans: counts only, for trails and replay
     verify   per source: verification summary, decile calibration
   computed by verify.js from data/recorded.json (HN, Show HN, GitHub
   scans recorded 2026-11-11) and data/backtest-*.json (Wikipedia days
   scored with the live method and checked against the next day).
   Run: node record.mjs build
   ============================================================ */

import fs from 'node:fs';
import path from 'node:path';
import { hydrate } from './history.js';
import { pairsFromScans, pairsFromBacktest, summarize, deciles } from './verify.js';
import { SOURCES, SOURCE_ORDER } from './constants.js';
import { clusterTopics } from './topics.js';
import { restingInputs } from './inputs.js';
import { engineReply } from './explain.js';

const round = (x, d = 4) => (Number.isFinite(x) ? Number(x.toFixed(d)) : x);

export async function build(DATA, HERE) {
  const rec = JSON.parse(fs.readFileSync(path.join(DATA, 'recorded.json'), 'utf8'));
  const allScans = rec.scans.slice().sort((a, b) => a.t - b.t);
  const replyFile = path.join(DATA, 'recorded-reply.json');
  const reply = fs.existsSync(replyFile) ? JSON.parse(fs.readFileSync(replyFile, 'utf8')) : null;
  const pinFile = path.join(DATA, 'pin.json');
  const pin = reply?.latestT || (fs.existsSync(pinFile) ? JSON.parse(fs.readFileSync(pinFile, 'utf8')).latestT : null);
  // the resting scan is pinned (to a recorded reply, or by data/pin.json) so it stays the scan the page describes
  const scans = pin ? allScans.filter((s) => s.t <= pin) : allScans;
  // latest: merge the newest record of each source into one resting scan
  const latestOf = {};
  for (const s of scans) for (const [src, v] of Object.entries(s.sources)) if (v.status === 'ok') latestOf[src] = s;
  const newest = scans[scans.length - 1];
  const latest = { ...newest, sources: {}, items: [], pools: {}, calls: {}, topics: [], origin: 'recorded' };
  for (const [src, s] of Object.entries(latestOf)) {
    latest.sources[src] = s.sources[src];
    latest.items.push(...s.items.filter((i) => i.src === src));
    if (s.calls?.[src]) latest.calls[src] = s.calls[src];
    latest.scalers = { ...(latest.scalers || {}), [src]: s.scalers?.[src] };
  }
  latest.t = Math.max(...Object.values(latest.sources).map((v) => v.fetchedAt || 0));
  latest.enabled = Object.keys(latest.sources);
  // trail: earlier scans, counts only
  const trail = scans.filter((s) => s !== newest).slice(-12).map((s) => ({
    t: s.t,
    obs: Object.fromEntries(Object.entries(s.sources).filter(([src, v]) => v.status === 'ok' && SOURCES[src].kind !== 'readership')
      .map(([src, v]) => [src, { at: v.fetchedAt, c: s.items.filter((i) => i.src === src).map((i) => [i.id, i.c]) }])),
  })).filter((s) => Object.keys(s.obs).length);
  // verification
  const hyd = allScans.map(hydrate);
  const verify = {};
  for (const src of ['hn', 'show', 'gh']) {
    const pairs = pairsFromScans(hyd, src);
    verify[src] = { kind: 'recorded scans', ...pack(pairs) };
  }
  for (const src of ['wen', 'wde', 'wes']) {
    const f = path.join(DATA, `backtest-${src}.json`);
    if (!fs.existsSync(f)) continue;
    const bt = JSON.parse(fs.readFileSync(f, 'utf8'));
    verify[src] = { kind: 'backtest', method: bt.method, written: bt.written, ...pack(pairsFromBacktest(bt)) };
  }
  const out = {
    format: 'lb.trending.archive', version: 2, written: new Date().toISOString(),
    recorded: { first: new Date(allScans[0].t).toISOString(), last: new Date(allScans[allScans.length - 1].t).toISOString(), scans: allScans.length, resting: new Date(newest.t).toISOString() },
    latest, trail, verify,
    reply: reply ? { model: reply.model, at: reply.at, ms: reply.ms, route: reply.route, json: reply.json } : null,
  };
  writeFixture(out, HERE, reply);
  const body = `/* ============================================================
   trending/archive.data.js — GENERATED by \`node record.mjs build\`.
   Real data recorded from public APIs, not typed by hand:
     Hacker News via the Algolia HN Search API; GitHub REST search;
     Wikimedia Analytics pageviews (CC0, Wikimedia Foundation).
   Recorded ${out.recorded.first} to ${out.recorded.last} (${allScans.length} scans).
   Raw inputs: data/recorded.json, data/backtest-*.json.
   ============================================================ */
export const ARCHIVE = ${JSON.stringify(out)};
`;
  fs.writeFileSync(path.join(HERE, 'archive.data.js'), body);
  console.log(`archive.data.js ${(body.length / 1024).toFixed(1)} KB; latest ${latest.items.length} items; trail ${trail.length}; verify ${Object.keys(verify).join(',')}`);
}

function pack(pairs) {
  const sum = summarize(pairs);
  const dec = deciles(pairs);
  for (const m of Object.values(sum.methods)) { m.rate = round(m.rate); if (m.ci) m.ci = m.ci.map((x) => round(x)); }
  if (sum.spearman) { sum.spearman.rho = round(sum.spearman.rho); if (sum.spearman.ci) sum.spearman.ci = sum.spearman.ci.map((x) => round(x)); }
  return {
    summary: sum,
    deciles: { n: dec.n, tooFew: dec.tooFew, edges: (dec.edges || []).map((x) => round(x)), bins: dec.bins.map((b) => ({ n: b.n, above: b.above, p: round(b.p) })) },
  };
}

/* The inputs the page builds for the resting scan, computed the same way (inputs.js). */
export function restingFor(archive) {
  const scan = hydrate(archive.latest);
  const enabled = new Set(SOURCE_ORDER.filter((s) => SOURCES[s].defaultOn));
  const { topics, terms } = clusterTopics(scan.items.filter((i) => enabled.has(i.src)));
  for (const it of scan.items) it.terms = terms.get(`${it.id}|${it.src}`) || it.terms || [];
  scan.topics = topics;
  const idx = new Map();
  for (const s of archive.trail || []) for (const [src, o] of Object.entries(s.obs)) for (const [id, c] of o.c) {
    const k = `${id}|${src}`;
    if (!idx.has(k)) idx.set(k, []);
    idx.get(k).push({ t: o.at, c });
  }
  const earlier = (it) => {
    const all = (idx.get(`${it.id}|${it.src}`) || []).filter((e) => e.t < it.t).sort((a, b) => a.t - b.t);
    const out = [];
    for (const e of all) if (!out.length || e.t - out[out.length - 1].t > 60000) out.push(e);
    return out;
  };
  return { scan, ...restingInputs(scan, enabled, earlier) };
}

/* fixtures.js: a recorded reply with two planted faults, for ?fixture and tests.mjs. */
function writeFixture(archive, HERE, reply) {
  const { scan, top, facts, ctxs, topics, scanFacts } = restingFor(archive);
  const base = reply?.json && Array.isArray(reply.json.signals) ? reply.json : engineReply(top, ctxs, topics, scan, {});
  const fx = JSON.parse(JSON.stringify(base));
  for (const e of fx.signals || []) delete e.rule;
  const s3 = (fx.signals || []).find((e) => e.id === 's3');
  if (s3) s3.cause = 'trending';                                   // fault 1: a cause off the fixed list
  const s2 = (fx.signals || []).find((e) => e.id === 's2');
  let planted = null;
  if (s2) {
    const fact = facts[1];
    const m = [...String(s2.why).matchAll(/(?<![\w.])\d[\d,]*(?:\.\d+)?/g)].find((x) => Number(x[0].replace(/,/g, '')) > 2);
    const wrong = fact ? Math.round((Number(fact[Object.keys(fact).find((k) => typeof fact[k] === 'number' && fact[k] > 10)] || 50) * 3.7) + 7) : 999;
    if (m) { planted = { was: m[0], now: String(wrong) }; s2.why = s2.why.replace(m[0], String(wrong)); }
    else { planted = { was: null, now: String(wrong) }; s2.why = `${s2.why} It gained ${wrong} in the last hour.`; }
  }
  const body = `/* ============================================================
   trending/fixtures.js — GENERATED by \`node record.mjs build\`.
   A TEST FIXTURE, not evidence: the ${reply ? `model reply recorded ${reply.at} (${reply.model}, ${reply.route})` : 'deterministic engine reply'}
   for the resting scan, with two faults planted on purpose:
     s3: cause "trending", which is not on the fixed list (schema fault)
     s2: the number ${planted?.was ?? '(none)'} replaced by ${planted?.now}, which is in no fact (fact-check fault)
   ?fixture loads it; tests.mjs checks that the page rejects s3 and flags s2.
   ============================================================ */
export const FIXTURE = ${JSON.stringify({ model: reply ? reply.model : 'deterministic engine', label: 'test fixture: recorded reply with two planted faults', planted, reply: fx })};
`;
  fs.writeFileSync(path.join(HERE, 'fixtures.js'), body);
}
