#!/usr/bin/env node
/* ============================================================
   honesty-decoder/snapshot.mjs — what the checks are checked against.

   For every file a row cites, records the last commit that touched it,
   that commit's date, a SHA-256 of its content (line endings
   normalised to LF, as the site serves it) and the line of every
   anchor. The page hashes what it fetches and compares: a match names
   the commit it checked; a mismatch says the lab changed since.

     node labs/assets/js/honesty-decoder/snapshot.mjs           refresh commits and hashes
     node labs/assets/js/honesty-decoder/snapshot.mjs --grade   also record them as the grading commit

   Writes labs/assets/js/honesty-decoder/data/snapshot.js.
   ============================================================ */

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..', '..', '..');
const OUT = path.join(HERE, 'data', 'snapshot.js');

const { ROWS, SHARED } = await import(pathToFileURL(path.join(HERE, 'registry.js')).href);

const git = (args) => execFileSync('git', args, { cwd: ROOT, encoding: 'utf8' }).trim();
const read = (f) => fs.readFileSync(path.join(ROOT, f), 'utf8').replace(/\r\n?/g, '\n');
export const sha256 = (text) => createHash('sha256').update(text, 'utf8').digest('hex');
const lineOf = (text, anchor) => {
  const i = text.indexOf(anchor);
  return i < 0 ? null : text.slice(0, i).split('\n').length;
};

const prev = fs.existsSync(OUT) ? (await import(pathToFileURL(OUT).href + '?' + Date.now())).SNAPSHOT : null;

const files = {};
const anchors = {};
const want = new Set();
for (const r of ROWS) {
  r.files.forEach((f) => want.add(f));
  for (const s of r.subs) for (const [f] of [...(s.ev || []), ...(s.absent || [])]) want.add(f);
}
for (const s of Object.values(SHARED)) for (const [f] of s.ev) want.add(f);
want.delete('labs/assets/js/honesty-decoder/data/snapshot.js');

for (const f of [...want].sort()) {
  if (!fs.existsSync(path.join(ROOT, f))) { files[f] = { missing: true }; continue; }
  const text = read(f);
  const log = git(['log', '-1', '--format=%h|%ad', '--date=short', '--', f]);
  const [commit, date] = log ? log.split('|') : ['uncommitted', ''];
  files[f] = { commit, date, sha256: sha256(text), bytes: Buffer.byteLength(text) };
}
for (const r of ROWS) {
  for (const s of r.subs) {
    for (const [f, a] of s.ev || []) {
      if (files[f]?.missing) continue;
      anchors[`${f}::${a}`] = lineOf(read(f), a);
    }
  }
}

/* A lab's commit: the newest commit over its own files. */
const labs = {};
for (const r of ROWS) {
  let best = null;
  for (const f of r.files) {
    const x = files[f];
    if (!x || x.missing) continue;
    if (!best || x.date > best.date || (x.date === best.date && f === r.files[0])) best = { commit: x.commit, date: x.date };
  }
  labs[r.id] = best;
}

const grade = process.argv.includes('--grade');
const grading = grade
  ? { date: new Date().toISOString().slice(0, 10), labs: Object.fromEntries(Object.entries(labs).map(([k, v]) => [k, v?.commit])) }
  : prev?.grading || null;

const head = git(['rev-parse', '--short', 'HEAD']);
const snap = { generated: new Date().toISOString().slice(0, 10), head, files, labs, grading, anchors };
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT,
  '/* Generated by labs/assets/js/honesty-decoder/snapshot.mjs. Do not edit by hand.\n' +
  '   Commit, date, LF-normalised SHA-256 and anchor lines of every file a decoder row cites. */\n' +
  `export const SNAPSHOT = ${JSON.stringify(snap, null, 1)};\n`);
const stale = grading ? Object.entries(labs).filter(([k, v]) => grading.labs[k] && v && grading.labs[k] !== v.commit).map(([k]) => k) : [];
console.log(`snapshot: ${Object.keys(files).length} files, ${Object.keys(anchors).length} anchors, head ${head}` +
  (grading ? `, graded ${grading.date}, stale ${stale.length ? stale.join(', ') : 'none'}` : ', not graded'));
